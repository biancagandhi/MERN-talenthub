const jwt = require('jsonwebtoken');
const User = require('../models/User');

const generateToken = (id) => {
  // INTENTIONAL ISSUE: Token never expires (no expiresIn)
  return jwt.sign({ id }, process.env.JWT_SECRET || 'fallback_secret');
};

// @desc    Login user
// @route   POST /api/auth/login
const login = async (req, res) => {
  // INTENTIONAL ISSUE: No rate limiting on login — brute force possible
  // INTENTIONAL ISSUE: No input sanitization
  const { email, password } = req.body;

  try {
    if (!email || !password) {
      return res.status(400).json({ message: 'Email and password required' });
    }

    const user = await User.findOne({ email });

    if (!user) {
      return res.status(401).json({ message: 'Invalid credentials' });
    }

    const isMatch = await user.matchPassword(password);

    if (!isMatch) {
      return res.status(401).json({ message: 'Invalid credentials' });
    }

    // Update last login
    user.lastLogin = new Date();
    await user.save();

    res.json({
      _id: user._id,
      name: user.name,
      email: user.email,
      role: user.role,
      department: user.department,
      token: generateToken(user._id),
    });
  } catch (error) {
    console.error(error);
    res.status(500).json({ message: 'Server error' });
  }
};

// @desc    Get current user
// @route   GET /api/auth/me
const getMe = async (req, res) => {
  try {
    const user = await User.findById(req.user._id);
    res.json(user);
  } catch (error) {
    res.status(500).json({ message: 'Server error' });
  }
};

// @desc    Register user (admin only in production but open for demo)
// @route   POST /api/auth/register
const register = async (req, res) => {
  // INTENTIONAL ISSUE: No authorization check — anyone can create admin accounts
  const { name, email, password, role, department } = req.body;

  try {
    const userExists = await User.findOne({ email });

    if (userExists) {
      return res.status(400).json({ message: 'User already exists' });
    }

    const user = await User.create({ name, email, password, role, department });

    res.status(201).json({
      _id: user._id,
      name: user.name,
      email: user.email,
      role: user.role,
      token: generateToken(user._id),
    });
  } catch (error) {
    console.error(error);
    res.status(500).json({ message: 'Server error' });
  }
};

module.exports = { login, getMe, register };
